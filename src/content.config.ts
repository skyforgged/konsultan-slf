import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';

const sharedIdentity = {
  id: z.number().int().positive(),
  ulid: z.string().length(26),
  title: z.string().min(1),
  description: z.string().min(1),
  draft: z.boolean().default(false),
  image: z.string().optional(),
};

const articles = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/articles' }),
  schema: z.object({
    ...sharedIdentity,
    type: z.literal('article'),
    schemaType: z.enum(['Article', 'BlogPosting', 'TechArticle', 'NewsArticle']).default('BlogPosting'),
    slug: z.string().min(1),
    pubDate: z.coerce.date(),
    updatedDate: z.coerce.date().optional(),
    author: z.string().optional(),
    category: z.string().optional(),
    tags: z.array(z.string()).default([]),
    relatedType: z.enum(['service', 'page', 'article']).optional(),
    relatedId: z.number().int().positive().optional(),
    relatedArticles: z.array(z.number().int().positive()).default([]),
    blocks: z.array(z.discriminatedUnion('component', [
      z.object({
        component: z.literal('card'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1),
        icon: z.string().optional(),
        class: z.record(z.string()).optional(),
        body: z.array(z.discriminatedUnion('type', [
          z.object({ type: z.literal('p'), text: z.string().min(1), class: z.string().optional() }),
          z.object({ type: z.literal('list'), ordered: z.boolean().default(false), items: z.array(z.string().min(1)).min(1), class: z.string().optional(), itemClass: z.string().optional() }),
          z.object({ type: z.literal('image'), src: z.string().min(1), alt: z.string().min(1), caption: z.string().optional(), class: z.string().optional(), imgClass: z.string().optional(), captionClass: z.string().optional() }),
        ])).default([]),
      }),
      z.object({
        component: z.literal('faq'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1),
        icon: z.string().optional(),
        class: z.record(z.string()).optional(),
        items: z.array(z.object({ question: z.string().min(1), answer: z.string().min(1) })).min(1),
      }),
      z.object({
        component: z.literal('cta'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1).optional(),
        icon: z.string().optional(),
        message: z.string().min(1),
        button: z.string().min(1).optional(),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('table'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1).optional(),
        icon: z.string().optional(),
        head: z.array(z.string().min(1)).min(1),
        rows: z.array(z.array(z.string().min(1))).min(1),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('note'),
        id: z.string().min(1).optional(),
        variant: z.enum(['info', 'success', 'warning', 'danger']).default('info'),
        title: z.string().min(1).optional(),
        text: z.string().min(1),
        icon: z.string().optional(),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('steps'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1),
        icon: z.string().optional(),
        items: z.array(z.object({ title: z.string().min(1), text: z.string().min(1) })).min(1),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('stats'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1).optional(),
        icon: z.string().optional(),
        items: z.array(z.object({ value: z.string().min(1), label: z.string().min(1) })).min(1),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('glossary'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1),
        icon: z.string().optional(),
        items: z.array(z.object({ term: z.string().min(1), definition: z.string().min(1) })).min(1),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('quote'),
        id: z.string().min(1).optional(),
        text: z.string().min(1),
        source: z.string().min(1).optional(),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('section'),
        id: z.string().min(1).optional(),
        heading: z.string().min(1),
        content: z.array(z.discriminatedUnion('type', [
          z.object({ type: z.literal('p'), text: z.string().min(1) }),
          z.object({ type: z.literal('list'), ordered: z.boolean().default(false), items: z.array(z.string().min(1)).min(1) }),
        ])).default([]),
        class: z.record(z.string()).optional(),
      }),
      z.object({
        component: z.literal('process-timeline'),
        id: z.string().min(1),
        title: z.string().min(1),
        steps: z.array(z.object({
          title: z.string().min(1),
          description: z.string().min(1),
        })).min(1),
      }),
      z.object({
        component: z.literal('checklist-card'),
        id: z.string().min(1),
        title: z.string().min(1),
        description: z.string().optional(),
        items: z.array(z.object({
          label: z.string().min(1),
          detail: z.string().optional(),
          required: z.boolean().optional(),
        })).min(1),
        note: z.string().optional(),
      }),
      z.object({
        component: z.literal('comparison-table'),
        id: z.string().min(1),
        title: z.string().min(1),
        intro: z.string().optional(),
        headers: z.array(z.string().min(1)).min(1),
        rows: z.array(z.array(z.string().min(1)).min(1)).min(1),
        note: z.string().optional(),
      }),
      z.object({
        component: z.literal('document-list'),
        id: z.string().min(1),
        title: z.string().min(1),
        intro: z.string().optional(),
        items: z.array(z.object({
          name: z.string().min(1),
          purpose: z.string().optional(),
          mandatory: z.boolean().optional(),
        })).min(1),
      }),
      z.object({
        component: z.literal('image-panel'),
        id: z.string().min(1),
        src: z.string().min(1),
        alt: z.string().min(1),
        caption: z.string().optional(),
      }),
      z.object({
        component: z.literal('feature-card-grid'),
        id: z.string().min(1),
        title: z.string().min(1),
        columns: z.union([z.literal(2), z.literal(3)]).default(3),
        items: z.array(z.object({
          title: z.string().min(1),
          description: z.string().optional(),
          points: z.array(z.string().min(1)).optional(),
        })).min(1),
      }),
      z.object({
        component: z.literal('stats-grid'),
        id: z.string().min(1),
        items: z.array(z.object({
          value: z.string().min(1),
          label: z.string().min(1),
        })).min(1),
      }),
    ])).default([]),
  }),
});

const pages = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/pages' }),
  schema: z.object({
    ...sharedIdentity,
    type: z.literal('page'),
    slug: z.string().min(1),
    pubDate: z.coerce.date().optional(),
    updatedDate: z.coerce.date().optional(),
    navLabel: z.string().optional(),
    seoTitle: z.string().optional(),
    keywords: z.array(z.string()).default([]),
  }),
});

const services = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/services' }),
  schema: z.object({
    ...sharedIdentity,
    type: z.literal('service'),
    slug: z.string().min(1),
    pubDate: z.coerce.date().optional(),
    updatedDate: z.coerce.date().optional(),
    serviceGroup: z.enum(['slf', 'pbg']).default('slf'),
    order: z.number().int().default(100),
    eyebrow: z.string().default('Layanan'),
    imageAlt: z.string().default('Ilustrasi layanan konsultasi'),
    intro: z.string().min(1),
    scopeTitle: z.string().default('Ruang lingkup pendampingan'),
    scope: z.array(z.string().min(1)).default([]),
    requirementsTitle: z.string().default('Persiapan konsultasi'),
    requirementsIntro: z.string().default('Informasi awal berikut membantu memetakan kebutuhan. Daftar final dapat berbeda sesuai kasus.'),
    requirements: z.array(z.string()).default([]),
    benefitsTitle: z.string().default('Manfaat pendampingan'),
    benefits: z.array(z.string()).default([]),
    processTitle: z.string().default('Tahapan pendampingan'),
    process: z.array(z.object({ title: z.string().min(1), text: z.string().min(1) })).default([]),
    notesTitle: z.string().default('Hal yang perlu diperhatikan'),
    notes: z.string().default(''),
    faqTitle: z.string().default('Pertanyaan umum'),
    faq: z.array(z.object({ question: z.string(), answer: z.string() })).default([]),
    asideTitle: z.string().default('Persiapan konsultasi'),
    asideDescription: z.string().default('Informasi awal berikut membantu memetakan kebutuhan.'),
    guideLinkLabel: z.string().default('Baca panduan'),
    guideLinkHref: z.string().default('/articles/'),
    ctaLabel: z.string().default('Konsultasikan Kebutuhan Anda'),
    ctaDescription: z.string().min(1),
    ctaLinkLabel: z.string().default('Baca panduan awal'),
    ctaHref: z.string().default('/articles/'),
    relatedArticlesTitle: z.string().default('Artikel terkait layanan'),
  }),
});

export const collections = { articles, pages, services };
